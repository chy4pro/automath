print("  l = sum_a/n = %d/%d = %s   mu = %d" % (sum_a, n, sum_a // n, a_min))
print("  rad = diam = %d   (eccentricity 5 at every one of the %d vertices)" % (rad, n))
print("  CONSTRUCTED path (G42's mechanism)  = %s vertices = rad + 4" %
      (len(constructed) if constructed else "NONE"))
